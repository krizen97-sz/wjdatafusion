import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import {
  copyFile,
  mkdir,
  readFile,
  readdir,
  unlink,
  writeFile
} from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const KEYLINE_VERSION = '0.1.4'
const KEYLINE_COMMIT = '403f023d0861d01807cdec045b5fb3fec984468d'
const KEYLINE_ICON_COUNT = 547
const KEYLINE_URL = 'https://github.com/keyline-icons/keyline-icons'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const projectDirectory = path.resolve(scriptDirectory, '..')
const targetIconDirectory = path.join(projectDirectory, 'src/assets/icons/svg/keyline')
const targetAssetDirectory = path.join(projectDirectory, 'src/assets/icons')
const targetCatalogFile = path.join(projectDirectory, 'src/components/IconSelect/keylineData.js')

function fail(message) {
  throw new Error(`[keyline-import] ${message}`)
}

function sourceFromArguments() {
  const sourceFlagIndex = process.argv.indexOf('--source')
  const source = sourceFlagIndex >= 0 ? process.argv[sourceFlagIndex + 1] : undefined
  if (!source) {
    fail('请通过 --source 指定 Keyline Icons 仓库目录')
  }
  return path.resolve(source)
}

function readSourceCommit(sourceDirectory) {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], {
      cwd: sourceDirectory,
      encoding: 'utf8'
    }).trim()
  } catch {
    fail('来源目录必须是可验证提交的 Git 仓库')
  }
}

function assertSafeSvg(fileName, source) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.svg$/.test(fileName)) {
    fail(`${fileName} 文件名不符合 kebab-case 约定`)
  }
  if (!source.includes('viewBox="0 0 24 24"')) {
    fail(`${fileName} 不是 24×24 图标`)
  }
  if (!source.includes('currentColor')) {
    fail(`${fileName} 未继承 currentColor`)
  }
  if (/<(?:script|foreignObject|image|style)\b|\b(?:href|xlink:href|class|id)=/i.test(source)) {
    fail(`${fileName} 包含平台图标不允许的外部内容或标识`)
  }
}

async function main() {
  const sourceDirectory = sourceFromArguments()
  const sourceIconDirectory = path.join(sourceDirectory, 'icons/stroke')
  const sourcePackageFile = path.join(sourceDirectory, 'packages/cli/package.json')
  const sourceKeywordsFile = path.join(sourceDirectory, 'lib/icon-keywords.json')
  const sourceAliasesFile = path.join(sourceDirectory, 'lib/icon-aliases.json')
  const sourceLicenseFile = path.join(sourceDirectory, 'LICENSE')

  const sourceCommit = readSourceCommit(sourceDirectory)
  if (sourceCommit !== KEYLINE_COMMIT) {
    fail(`提交不匹配：期望 ${KEYLINE_COMMIT}，实际 ${sourceCommit}`)
  }

  const sourcePackage = JSON.parse(await readFile(sourcePackageFile, 'utf8'))
  if (sourcePackage.version !== KEYLINE_VERSION) {
    fail(`版本不匹配：期望 ${KEYLINE_VERSION}，实际 ${sourcePackage.version}`)
  }

  const sourceIcons = (await readdir(sourceIconDirectory))
    .filter((fileName) => fileName.endsWith('.svg'))
    .sort((left, right) => left.localeCompare(right))

  if (sourceIcons.length !== KEYLINE_ICON_COUNT) {
    fail(`图标数量不匹配：期望 ${KEYLINE_ICON_COUNT}，实际 ${sourceIcons.length}`)
  }

  const aggregateHash = createHash('sha256')
  const validatedIcons = []
  for (const fileName of sourceIcons) {
    const source = await readFile(path.join(sourceIconDirectory, fileName), 'utf8')
    assertSafeSvg(fileName, source)
    aggregateHash.update(fileName)
    aggregateHash.update('\0')
    aggregateHash.update(source)
    aggregateHash.update('\0')
    validatedIcons.push({ fileName, source })
  }

  await mkdir(targetIconDirectory, { recursive: true })
  const existingIcons = (await readdir(targetIconDirectory)).filter((fileName) => fileName.endsWith('.svg'))
  const sourceIconSet = new Set(sourceIcons)
  for (const fileName of existingIcons) {
    if (!sourceIconSet.has(fileName)) {
      await unlink(path.join(targetIconDirectory, fileName))
    }
  }
  for (const { fileName } of validatedIcons) {
    await copyFile(path.join(sourceIconDirectory, fileName), path.join(targetIconDirectory, fileName))
  }

  const keywordData = JSON.parse(await readFile(sourceKeywordsFile, 'utf8'))
  const aliasData = JSON.parse(await readFile(sourceAliasesFile, 'utf8'))
  const generatedCatalog = [
    '// Generated by scripts/import-keyline-icons.mjs. Do not edit by hand.',
    `export const keylineKeywords = ${JSON.stringify(keywordData.keywords)}`,
    `export const keylineAliases = ${JSON.stringify(aliasData.aliases)}`,
    ''
  ].join('\n')
  await writeFile(targetCatalogFile, generatedCatalog, 'utf8')

  await copyFile(sourceLicenseFile, path.join(targetAssetDirectory, 'KEYLINE_LICENSE.txt'))
  await writeFile(
    path.join(targetAssetDirectory, 'KEYLINE_NOTICE.txt'),
    [
      'Keyline Icons',
      `Source: ${KEYLINE_URL}`,
      `Package version: ${KEYLINE_VERSION}`,
      `Pinned commit: ${KEYLINE_COMMIT}`,
      `Imported scope: ${KEYLINE_ICON_COUNT} stroke SVG icons`,
      'Local symbol prefix: keyline-',
      'License: MIT (see KEYLINE_LICENSE.txt)',
      '',
      'The source project states that its license covers the icons and code but does not',
      'grant rights in the name “Keyline Icons”. The product UI uses the neutral label',
      '“扩展图标”; the upstream name is retained here only for third-party notices.',
      ''
    ].join('\n'),
    'utf8'
  )

  const manifest = {
    name: 'Keyline Icons',
    source: KEYLINE_URL,
    packageVersion: KEYLINE_VERSION,
    commit: KEYLINE_COMMIT,
    style: 'stroke',
    iconCount: KEYLINE_ICON_COUNT,
    symbolPrefix: 'keyline-',
    aggregateSha256: aggregateHash.digest('hex')
  }
  await writeFile(
    path.join(targetAssetDirectory, 'KEYLINE_MANIFEST.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8'
  )

  console.log(`Imported ${sourceIcons.length} Keyline stroke icons from ${sourceCommit.slice(0, 8)}.`)
  console.log(`Target: ${targetIconDirectory}`)
}

await main()
